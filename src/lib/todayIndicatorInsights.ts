function relativeMoveText(relativeMove: number) {
  if (!Number.isFinite(relativeMove) || relativeMove < 1.5) return '最近の動きの中で目立つ変化です。';
  if (relativeMove >= 10) return '普段の10倍以上の変化です。';
  return `普段の約${relativeMove.toFixed(1)}倍の変化です。`;
}

export function getTodayIndicatorInsight(selection: TodayIndicatorSelection) {
  const guide = insights.get(selection.id);
  if (!guide) return null;
  const directionText = selection.direction > 0 ? guide.up : selection.direction < 0 ? guide.down : (guide.flat ?? '前回と同じ水準です。次の更新を待って確認します。');
  return `${relativeMoveText(selection.relativeMove)}${directionText}`;
}

